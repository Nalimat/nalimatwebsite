import { site } from "@/content/site";

/**
 * Page metadata, mirroring what the Next.js Metadata API produced.
 *
 * Static tags shared by every page (charset, viewport, theme-color,
 * application-name, robots, icon, Organization JSON-LD) live in index.html.
 * Everything that varies per page is rendered by <Seo> (React 19 hoists
 * <title>, <meta> and <link> into <head>, and the build-time prerender
 * writes them into each page's static HTML).
 */
export type Meta = { name?: string; property?: string; content: string };

export type SeoData = {
  title: string;
  description: string;
  /** Absolute canonical URL, or omitted for no canonical link. */
  canonical?: string;
  meta: Meta[];
};

const absolute = (path: string) => (path === "/" || path === "" ? site.url : `${site.url}${path}`);
const defaultTitle = `${site.name} | ${site.tagline}`;
const imageAlt = `${site.name}: ${site.tagline}`;

/** The social image (formerly generated by src/app/opengraph-image.tsx). */
const ogImage: Meta[] = [
  { property: "og:image", content: `${site.url}/og-image.png` },
  { property: "og:image:type", content: "image/png" },
  { property: "og:image:width", content: "1200" },
  { property: "og:image:height", content: "630" },
  { property: "og:image:alt", content: imageAlt },
];
const twitterImage: Meta[] = [
  { name: "twitter:image", content: `${site.url}/og-image.png` },
  { name: "twitter:image:alt", content: imageAlt },
  { name: "twitter:image:type", content: "image/png" },
  { name: "twitter:image:width", content: "1200" },
  { name: "twitter:image:height", content: "630" },
];

/** Site-wide defaults (root layout metadata): used by the homepage and the 404 page. */
export function defaultMetadata({ title, noindex }: { title?: string; noindex?: boolean } = {}): SeoData {
  return {
    title: title ? `${title} | ${site.name}` : defaultTitle,
    description: site.description,
    canonical: absolute("/"),
    meta: [
      ...(noindex ? [{ name: "robots", content: "noindex" }] : []),
      { property: "og:title", content: defaultTitle },
      { property: "og:description", content: site.description },
      { property: "og:url", content: absolute("/") },
      { property: "og:site_name", content: site.name },
      { property: "og:locale", content: site.locale },
      ...ogImage,
      { property: "og:type", content: "website" },
      { name: "twitter:card", content: "summary_large_image" },
      { name: "twitter:title", content: site.name },
      { name: "twitter:description", content: site.description },
      ...twitterImage,
    ],
  };
}

/**
 * Per-page metadata with consistent Open Graph and Twitter tags, including the
 * shared Nalimat social image (the Next.js version omitted it on inner pages).
 */
export function pageMetadata({
  title,
  description,
  path,
}: {
  title: string;
  description: string;
  path: string;
}): SeoData {
  const full = `${title} | ${site.name}`;
  return {
    title: full,
    description,
    canonical: absolute(path),
    meta: [
      { property: "og:title", content: full },
      { property: "og:description", content: description },
      { property: "og:url", content: absolute(path) },
      { property: "og:site_name", content: site.name },
      { property: "og:locale", content: site.locale },
      ...ogImage,
      { property: "og:type", content: "website" },
      { name: "twitter:card", content: "summary_large_image" },
      { name: "twitter:title", content: full },
      { name: "twitter:description", content: description },
      ...twitterImage,
    ],
  };
}

/** Article metadata (insight posts): page metadata with an article Open Graph block. */
export function articleMetadata(post: {
  title: string;
  excerpt: string;
  slug: string;
  date: string;
  author: string;
}): SeoData {
  const base = pageMetadata({ title: post.title, description: post.excerpt, path: `/insights/${post.slug}` });
  return {
    ...base,
    meta: [
      { property: "og:title", content: post.title },
      { property: "og:description", content: post.excerpt },
      { property: "og:url", content: absolute(`/insights/${post.slug}`) },
      ...ogImage,
      { property: "og:type", content: "article" },
      { property: "article:published_time", content: post.date },
      { property: "article:author", content: post.author },
      ...base.meta.filter((m) => m.name?.startsWith("twitter:")),
    ],
  };
}
